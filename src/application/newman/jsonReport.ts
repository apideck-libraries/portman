import fs from 'fs-extra'
import path from 'path'
import { Item } from 'postman-collection'
import { OasMappedOperation } from '../../oas'
import { PostmanMappedOperation } from '../../postman'

/**
 * Machine-readable run report, written by `--jsonReport <path>` after a Newman run.
 * The shape is versioned: breaking changes bump `version`, additive changes do not.
 */
export const JSON_REPORT_VERSION = 1

export type JsonReportTestType =
  | 'schemaValidation'
  | 'statusSuccess'
  | 'statusCode'
  | 'contentType'
  | 'jsonBody'
  | 'headersPresent'
  | 'responseTime'
  | 'content'
  | 'variation'
  | 'unknown'

export type JsonReportFailureType = 'assertion' | 'requestError' | 'scriptError' | 'other'

export interface JsonReportFailure {
  request: string | null
  method: string | null
  url: string | null
  openApiOperation: string | null
  openApiOperationId: string | null
  variation: boolean
  failureType: JsonReportFailureType
  assertion: string | null
  testType: JsonReportTestType | null
  message: string
  response: {
    status: number
    responseTime: number
    body: string | null
    bodyTruncated: boolean
  } | null
}

export interface JsonReport {
  version: number
  portmanVersion: string
  spec: string | null
  baseUrl: string | null
  startedAt: string | null
  finishedAt: string | null
  summary: {
    requests: number
    assertions: number
    failedAssertions: number
    failures: number
    passed: boolean
  }
  runError: string | null
  failures: JsonReportFailure[]
}

export interface JsonReportContext {
  spec?: string
  baseUrl?: string
  /** OpenAPI operations keyed by pathRef ("GET::/crm/leads/{id}"), see OpenApiParser.operationIdMap */
  operationIdMap?: Record<string, OasMappedOperation>
  /** globals.separatorSymbol, defaults to "::" */
  separatorSymbol?: string
  /** Folder name Portman uses for variation tests */
  variationFolderName?: string
  portmanVersion?: string
}

export const RESPONSE_BODY_LIMIT = 4096

// Titles generated by src/application/tests/*, matched on the part after "[METHOD]::/path - "
const TEST_TYPE_PATTERNS: [RegExp, JsonReportTestType][] = [
  [/^Schema is valid$/, 'schemaValidation'],
  [/^Status code is 2xx$/, 'statusSuccess'],
  [/^Response status code is \d+/, 'statusCode'],
  [/^Content-Type is /, 'contentType'],
  [/^Response has (JSON|empty) Body$/, 'jsonBody'],
  [/^Response header .+ is present$/, 'headersPresent'],
  [/^Response time is less than \d+ms$/, 'responseTime'],
  [/^Content check if /, 'content'],
  [/^Response header .+ /, 'content']
]

const escapeRegExp = (value: string): string => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/**
 * Split a Portman assertion title ("[GET]::/crm/leads/:id - Schema is valid") into its parts.
 */
export const parseAssertionTitle = (
  title: string,
  separatorSymbol = '::'
): { method: string; path: string; check: string } | null => {
  const re = new RegExp(`^\\[([A-Za-z]+)\\]${escapeRegExp(separatorSymbol)}(\\S*) - ([\\s\\S]+)$`)
  const match = title.match(re)
  if (!match) return null
  return { method: match[1].toUpperCase(), path: match[2], check: match[3] }
}

export const inferTestType = (
  title: string | null | undefined,
  separatorSymbol = '::',
  variation = false
): JsonReportTestType => {
  const parsed = title ? parseAssertionTitle(title, separatorSymbol) : null
  if (parsed) {
    const hit = TEST_TYPE_PATTERNS.find(([re]) => re.test(parsed.check))
    if (hit) return hit[1]
  }
  return variation ? 'variation' : 'unknown'
}

/** Convert a Postman path ("/crm/leads/:id") into an OpenAPI pathRef ("GET::/crm/leads/{id}") */
const toPathRef = (method: string, pmPath: string): string => {
  const oaPath = pmPath
    .split('/')
    .map(segment => (segment.startsWith(':') ? `{${segment.slice(1)}}` : segment))
    .map(segment => segment.replace('{{', '{').replace('}}', '}'))
    .join('/')
  return `${method.toUpperCase()}::${oaPath}`
}

const resolveOperation = (
  item: unknown,
  title: string | null,
  context: JsonReportContext
): { openApiOperation: string | null; openApiOperationId: string | null } => {
  const operationIdMap = context.operationIdMap || {}
  let pathRef: string | null = null

  // Preferred: reuse PostmanMappedOperation, the same mapping Portman uses when injecting tests
  if (item && Item.isItem(item)) {
    try {
      const pmOperation = new PostmanMappedOperation({ item: item as Item, operationIdMap })
      pathRef = pmOperation.pathRef
      if (pmOperation.id || operationIdMap[pathRef]) {
        return {
          openApiOperation: operationIdMap[pathRef]?.pathRef || pathRef,
          openApiOperationId: pmOperation.id || operationIdMap[pathRef]?.id || null
        }
      }
    } catch (_e) {
      // fall through to title based mapping
    }
  }

  // Fallback: the "[GET]::/path" prefix of Portman assertion titles
  const parsed = title ? parseAssertionTitle(title, context.separatorSymbol) : null
  if (parsed) {
    const titleRef = toPathRef(parsed.method, parsed.path)
    if (operationIdMap[titleRef]) {
      return { openApiOperation: titleRef, openApiOperationId: operationIdMap[titleRef].id || null }
    }
    pathRef = pathRef || titleRef
  }

  return { openApiOperation: pathRef, openApiOperationId: null }
}

const isInVariationFolder = (item: unknown, folderName: string): boolean => {
  let parent = (item as { parent?: () => unknown })?.parent?.()
  while (parent) {
    if ((parent as { name?: string }).name === folderName) return true
    const next = (parent as { parent?: () => unknown }).parent
    parent = typeof next === 'function' ? next.call(parent) : undefined
  }
  return false
}

const responseBody = (response: any): { body: string | null; bodyTruncated: boolean } => {
  let body: string | null = null
  try {
    body = typeof response?.text === 'function' ? response.text() : null
  } catch (_e) {
    body = null
  }
  if (body == null && response?.stream) {
    body = Buffer.from(response.stream).toString()
  }
  if (body == null) return { body: null, bodyTruncated: false }
  return body.length > RESPONSE_BODY_LIMIT
    ? { body: body.slice(0, RESPONSE_BODY_LIMIT), bodyTruncated: true }
    : { body, bodyTruncated: false }
}

const toIso = (ms: unknown): string | null =>
  typeof ms === 'number' && ms > 0 ? new Date(ms).toISOString() : null

const failureTypeFor = (failure: any): JsonReportFailureType => {
  const at = String(failure?.at || '')
  if (failure?.error?.name === 'AssertionError' || at.startsWith('assertion')) return 'assertion'
  if (at.startsWith('request')) return 'requestError'
  if (at.includes('script')) return 'scriptError'
  return 'other'
}

/**
 * Build the JSON run report from the summary Newman passes to its 'done' event.
 */
export const buildJsonReport = (
  newmanSummary: unknown,
  context: JsonReportContext = {},
  runError?: Error | null
): JsonReport => {
  // Newman's summary is loosely typed (postman-collection objects, serialised errors)
  const summary = newmanSummary as any
  const run = summary?.run || {}
  const stats = run.stats || {}
  const executions: any[] = Array.isArray(run.executions) ? run.executions : []
  const runFailures: any[] = Array.isArray(run.failures) ? run.failures : []
  const separatorSymbol = context.separatorSymbol || '::'
  const variationFolderName = context.variationFolderName || 'Variation Tests'

  const executionByRef = new Map<string, any>()
  executions.forEach(execution => {
    const ref = execution?.cursor?.ref
    if (ref) executionByRef.set(ref, execution)
  })

  // With abortOnFailure, postman-runtime re-throws a failed assertion as an extra
  // 'AssertionFailure' test-script error (message = assertion title). Drop that duplicate.
  const isAbortDuplicate = (failure: any): boolean =>
    failure?.error?.name === 'AssertionFailure' &&
    runFailures.some(
      other =>
        other !== failure &&
        other?.error?.name === 'AssertionError' &&
        other?.error?.test === failure?.error?.message &&
        other?.cursor?.ref === failure?.cursor?.ref
    )

  const failures: JsonReportFailure[] = runFailures
    .filter(f => !isAbortDuplicate(f))
    .map(failure => {
      const execution = executionByRef.get(failure?.cursor?.ref)
      const item = execution?.item || failure?.source
      const request = execution?.request || item?.request
      const response = execution?.response
      const failureType = failureTypeFor(failure)
      const assertion = failureType === 'assertion' ? failure?.error?.test || null : null
      const variation = isInVariationFolder(item, variationFolderName)

      let url: string | null = null
      try {
        url = request?.url ? request.url.toString() : null
      } catch (_e) {
        url = null
      }

      return {
        request: item?.name ?? null,
        method: request?.method ? String(request.method).toUpperCase() : null,
        url,
        ...resolveOperation(item, assertion, { ...context, separatorSymbol }),
        variation,
        failureType,
        assertion,
        testType:
          failureType === 'assertion' ? inferTestType(assertion, separatorSymbol, variation) : null,
        message: String(failure?.error?.message ?? failure?.error ?? ''),
        response: response
          ? {
              status: response.code,
              responseTime: response.responseTime,
              ...responseBody(response)
            }
          : null
      }
    })

  const failedAssertions = Number(stats?.assertions?.failed || 0)
  const errorMessage = runError?.message || summary?.error?.message || null

  return {
    version: JSON_REPORT_VERSION,
    portmanVersion: context.portmanVersion || getPortmanVersion(),
    spec: context.spec || null,
    baseUrl: context.baseUrl || null,
    startedAt: toIso(run?.timings?.started),
    finishedAt: toIso(run?.timings?.completed),
    summary: {
      requests: Number(stats?.requests?.total || 0),
      assertions: Number(stats?.assertions?.total || 0),
      failedAssertions,
      failures: failures.length,
      passed: !errorMessage && failedAssertions === 0 && runFailures.length === 0
    },
    runError: errorMessage,
    failures
  }
}

export const writeJsonReport = (reportPath: string, report: JsonReport): void => {
  const target = path.resolve(reportPath)
  fs.ensureDirSync(path.dirname(target))
  fs.writeFileSync(target, JSON.stringify(report, null, 2) + '\n')
}

let cachedVersion: string | undefined

export const getPortmanVersion = (): string => {
  if (cachedVersion) return cachedVersion
  // Walk up from this file (src/... or dist/...) to Portman's own package.json
  let dir = __dirname
  for (let i = 0; i < 6; i++) {
    const candidate = path.join(dir, 'package.json')
    try {
      const pkg = JSON.parse(fs.readFileSync(candidate, 'utf8'))
      if (pkg?.name === '@apideck/portman') {
        cachedVersion = String(pkg.version)
        return cachedVersion
      }
    } catch (_e) {
      // keep walking
    }
    dir = path.dirname(dir)
  }
  return 'unknown'
}
